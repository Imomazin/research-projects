"""Independent reproduction of the original study outputs (commit ed1a1df).

The script exports the project folder at the stated commit into an empty working
folder, deletes every derived output (sampling frame outputs, derived datasets,
results, manuscript numbers and blocks), reruns the full pipeline from the raw
inputs and compares every reproduced output with the committed one.

Raw inputs kept: Frame Candidates.csv and Filings Index.csv (written by the SEC
collection stages), the Raw Macro provider files, the filing texts and XBRL company
facts on branch data/strategic-risk, and the coder labels of the two audit files
(annotations cannot be regenerated by code).

Usage:
    python "reproduce study.py" --data "<clone of data/strategic-risk>" --work "<empty folder>"

Outputs (in this folder):
    Reconciliation Report.csv   one row per reported quantity: original, reproduced, difference, status
    File Comparison.csv         one row per derived file: rows, columns, maximum absolute difference
    Reproduction Summary.json   counts of matches and mismatches by source
"""
import argparse
import gzip
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
PROJ = HERE.parent
REPO = PROJ.parents[2]
REL = PROJ.relative_to(REPO).as_posix()
COMMIT = "ed1a1df"

DERIVED_OUTPUTS = [
    "Datasets/Sampling Frame/Eligible Frame.csv", "Datasets/Sampling Frame/Sample Firms.csv",
    "Datasets/Sampling Frame/Sample Selection Log.csv", "Datasets/Sampling Frame/Sample Allocation.csv",
    "Manuscript/Numbers.json", "Manuscript/Manuscript Blocks.json",
]
KEEP_DERIVED = {"Validation Audit Original Dictionary.csv", "Validation Holdout Revised Dictionary.csv"}


def export_commit(work: Path) -> Path:
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    tar = subprocess.run(["git", "archive", "--format=tar", COMMIT, REL], cwd=REPO, capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(tar)) as t:
        t.extractall(work, filter="data")
    root = work / REL
    for rel in DERIVED_OUTPUTS:
        (root / rel).unlink(missing_ok=True)
    for f in (root / "Datasets" / "Derived").glob("*.csv"):
        if f.name not in KEEP_DERIVED:
            f.unlink()
    for f in (root / "Results").rglob("*"):
        if f.is_file() and f.name != "build workbook.py":
            f.unlink()
    for f in root.rglob("__pycache__"):
        shutil.rmtree(f, ignore_errors=True)
    return root


def run(root: Path, script: str, *args, env=None, log=None):
    t0 = time.time()
    e = {**os.environ, **(env or {})}
    cmd = [sys.executable if not script.endswith(".js") else "node", str(root / script), *map(str, args)]
    r = subprocess.run(cmd, cwd=root / Path(script).parent, env=e, capture_output=True, text=True)
    log.append({"script": script, "args": " ".join(map(str, args)), "env": json.dumps(env or {}),
                "returncode": r.returncode, "seconds": round(time.time() - t0, 1),
                "stderr_tail": r.stderr[-600:]})
    if r.returncode:
        raise RuntimeError(f"{script} failed:\n{r.stderr[-3000:]}")
    return r.stdout


def audit_summary(path: Path) -> pd.DataFrame:
    a = pd.read_csv(path)
    lab = a["dictionary_label"].astype(str).str.replace(r"^action:.*", "action", regex=True)
    return a.assign(dictionary_label=lab).groupby("dictionary_label")["audit_label"].agg(["mean", "sum", "count"]).round({"mean": 3})


def pipeline(root: Path, data: Path, resume: bool = False) -> list:
    """Run the first-version pipeline. With resume, steps whose outputs already exist in the work
    folder from an interrupted run are recorded as reused instead of being run again."""
    log: list = []
    der = root / "Datasets" / "Derived"
    texts, facts = data / "Filing Texts", data / "Company Facts" / "Financial Facts Long.csv.gz"

    def done(step, *outs):
        if resume and all(o.exists() for o in outs):
            log.append({"script": step, "args": "", "env": "", "returncode": 0, "seconds": 0,
                        "stderr_tail": "reused output of the interrupted run in the same work folder"})
            return True
        return False

    if not done("Data Collection/draw sample.py", root / "Datasets" / "Sampling Frame" / "Sample Firms.csv"):
        run(root, "Data Collection/draw sample.py", log=log)
    # At ed1a1df no script writes the final row of the sample selection log (the validation screen
    # that leaves 787 firms); it was added to the committed log by hand. The reproduction derives it
    # from the committed Frame Validation Exclusions.csv and records this in the run log.
    sel = root / "Datasets" / "Sampling Frame" / "Sample Selection Log.csv"
    sl = pd.read_csv(sel)
    if len(sl) == 9:
        firms = pd.read_csv(root / "Datasets" / "Sampling Frame" / "Sample Firms.csv")
        exc = pd.read_csv(root / "Datasets" / "Sampling Frame" / "Frame Validation Exclusions.csv")
        n = int(len(set(firms["cik"]) - set(exc["cik"])))
        sl.loc[len(sl)] = ["Validation screen: implausible public float tags, non-US-dollar reporters and blank-check "
                           "companies (see Frame Validation Exclusions.csv)", n]
        sl.to_csv(sel, index=False)
        log.append({"script": "reproduce study.py (selection log)", "args": "", "env": "", "returncode": 0, "seconds": 0,
                    "stderr_tail": f"final selection-log row derived from Frame Validation Exclusions.csv: {n} firms; no script wrote it at ed1a1df"})
    if not done("Analysis/build financial panel.py", der / "Financial Panel.csv"):
        run(root, "Analysis/build financial panel.py", facts, der / "Financial Panel.csv", log=log)
    if not done("Analysis/build text measures.py", der / "Text Measures.csv", der / "Category Pairs.csv"):
        run(root, "Analysis/build text measures.py", texts, der, log=log)
    if not done("Analysis/build text measures.py (original dictionary)", der / "Text Measures Original Dictionary.csv"):
        tmp = root / "Original Dictionary Run"
        tmp.mkdir(exist_ok=True)
        run(root, "Analysis/build text measures.py", texts, tmp, env={"RISK_DICTIONARY": "Risk Taxonomy Dictionary Original.json"}, log=log)
        shutil.move(tmp / "Text Measures.csv", der / "Text Measures Original Dictionary.csv")
        shutil.move(tmp / "Validation Sample.csv", der / "Validation Sample Original Dictionary.csv")
    if resume:
        # the holdout draw only re-creates the audit sample, whose coded file is kept from the commit
        log.append({"script": "Analysis/build text measures.py (holdout seed)", "args": "", "env": "", "returncode": 0, "seconds": 0,
                    "stderr_tail": "not rerun on resume: its output is not used by later steps or compared"})
    else:
        hold = root / "Holdout Sample Run"
        hold.mkdir()
        run(root, "Analysis/build text measures.py", texts, hold, env={"VALIDATION_SEED": "20261025"}, log=log)
    run(root, "Analysis/build updating measure.py", texts, der / "Updating Measure.csv", log=log)
    run(root, "Analysis/build macro series.py", log=log)
    run(root, "Analysis/assemble panel.py", log=log)
    run(root, "Analysis/assemble panel.py", env={"TEXT_FILE": "Text Measures Original Dictionary.csv",
                                                 "PANEL_FILE": "Research Panel Original Dictionary.csv"}, log=log)
    run(root, "Analysis/estimate models.py", log=log)
    run(root, "Analysis/estimate models.py", env={"PANEL_FILE": "Research Panel Original Dictionary.csv",
                                                  "RESULTS_SUFFIX": "Original Dictionary"}, log=log)
    run(root, "Analysis/validate measures.py", log=log)
    run(root, "Analysis/select cases.py", texts, log=log)
    audit_summary(der / "Validation Audit Original Dictionary.csv").to_csv(root / "Results" / "Validation Audit Original Dictionary.csv")
    audit_summary(der / "Validation Holdout Revised Dictionary.csv").to_csv(root / "Results" / "Validation Audit Revised Dictionary Holdout.csv")
    run(root, "Manuscript/collect numbers.py", log=log)
    run(root, "Manuscript/build blocks.py", log=log)
    return log


def compare_frames(a: pd.DataFrame, b: pd.DataFrame) -> dict:
    out = {"rows_original": len(a), "rows_reproduced": len(b), "cols_original": a.shape[1], "cols_reproduced": b.shape[1]}
    if list(a.columns) != list(b.columns) or len(a) != len(b):
        out.update(identical=False, max_abs_diff=np.nan, note="shape or column names differ")
        return out
    num = a.select_dtypes("number").columns
    diff = 0.0
    for c in num:
        x, y = pd.to_numeric(a[c], errors="coerce"), pd.to_numeric(b[c], errors="coerce")
        if (x.isna() != y.isna()).any():
            out.update(identical=False, max_abs_diff=np.nan, note=f"missing pattern differs in {c}")
            return out
        diff = max(diff, float(np.nanmax(np.abs(x - y))) if x.notna().any() else 0.0)
    other = [c for c in a.columns if c not in num]
    # compare text with missing values made equal (under pandas 3 astype(str) keeps NaN, and NaN != NaN)
    same_text = all((a[c].fillna("").astype(str).values == b[c].fillna("").astype(str).values).all() for c in other)
    out.update(identical=bool(diff < 1e-9 and same_text), max_abs_diff=diff,
               note="" if same_text else "text columns differ")
    return out


def flatten(obj, prefix=""):
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from flatten(v, f"{prefix}/{k}" if prefix else str(k))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from flatten(v, f"{prefix}[{i}]")
    else:
        yield prefix, obj


def explain(key: str) -> str:
    if key.startswith("xbrl_fact_rows"):
        return "Typed as a constant in collect numbers.py; checked separately against a row count of the facts file"
    return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True, type=Path)
    ap.add_argument("--work", required=True, type=Path)
    ap.add_argument("--skip-run", action="store_true")
    ap.add_argument("--resume", action="store_true", help="continue an interrupted run in the same work folder")
    a = ap.parse_args()
    root = a.work / REL
    if not a.skip_run:
        root = root if a.resume else export_commit(a.work)
        log = pipeline(root, a.data, resume=a.resume)
        pd.DataFrame(log).to_csv(HERE / "Reproduction Run Log.csv", index=False)

    # ---------------- file-level comparison against the committed outputs at the same commit
    files = []
    committed = Path(a.work.parent / "Committed Outputs")
    if committed.exists():
        shutil.rmtree(committed)
    tar = subprocess.run(["git", "archive", "--format=tar", COMMIT, REL], cwd=REPO, capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(tar)) as t:
        t.extractall(committed, filter="data")
    croot = committed / REL
    targets = sorted([p.relative_to(croot) for p in croot.rglob("*.csv")
                      if p.parts[len(croot.parts)] in ("Datasets", "Results") and "Raw Macro" not in p.parts
                      and p.name not in ("Frame Candidates.csv", "Filings Index.csv", "Data Dictionary.csv", "Dataset Manifest.csv",
                                         "Frame Validation Exclusions.csv") and p.name not in KEEP_DERIVED])
    for rel in targets:
        o, r = croot / rel, root / rel
        row = {"file": rel.as_posix()}
        if not r.exists():
            row.update(identical=False, note="not reproduced")
        else:
            row.update(compare_frames(pd.read_csv(o, low_memory=False), pd.read_csv(r, low_memory=False)))
        files.append(row)
    for rel in ["Results/Model Results.json", "Results/Measure Validation.json", "Results/Illustrative Cases.json",
                "Results/Alternative Original Dictionary/Model Results.json"]:
        o, r = json.loads((croot / rel).read_text()), json.loads((root / rel).read_text())
        fo, fr = dict(flatten(o)), dict(flatten(r))
        nd = [k for k in fo if k not in fr or (isinstance(fo[k], (int, float)) and isinstance(fr.get(k), (int, float))
                                              and not (np.isnan(fo[k]) and np.isnan(fr[k])) and abs(fo[k] - fr[k]) > 1e-9)
              or (not isinstance(fo[k], (int, float)) and fo[k] != fr.get(k))]
        extra = [k for k in fr if k not in fo]
        files.append({"file": rel, "rows_original": len(fo), "rows_reproduced": len(fr), "identical": not nd and len(fo) == len(fr),
                      "note": f"{len(nd)} committed leaves differ" + (": " + "; ".join(nd[:5]) if nd else "") +
                              (f"; {len(extra)} additional leaves in the reproduction, e.g. {', '.join(extra[:3])}" if extra else "")})
    bo = json.loads((croot / "Manuscript/Manuscript Blocks.json").read_text())
    br = json.loads((root / "Manuscript/Manuscript Blocks.json").read_text())
    files.append({"file": "Manuscript/Manuscript Blocks.json", "identical": bo == br,
                  "note": "manuscript text and tables rebuilt from reproduced numbers" + ("" if bo == br else ": text differs")})
    why = {
        "Datasets/Derived/Validation Sample Original Dictionary.csv":
            ("Same 520 sentences; the committed file has an id column added when the sample was coded for the audit", "None needed"),
        "Datasets/Derived/Validation Sample.csv":
            ("Uncoded sample from the main text run; the committed draw shares 4 of 520 sentences with the reproduction, probably because it was written before the "
             "final dictionary edit changed which sentences consume random draws. No reported number uses this file: the revised-dictionary audit uses the committed "
             "Validation Holdout Revised Dictionary.csv", "Reproduced file kept in the work folder; committed file left unchanged"),
        "Datasets/Sampling Frame/Sample Selection Log.csv":
            ("Same counts. The first-row label in the committed log omits '(from frame stage log)' and the final row (787 firms) was added by hand; no script wrote it at ed1a1df",
             "The reproduction derives the final row from Frame Validation Exclusions.csv"),
        "Results/Alternative Original Dictionary/Model Results.json":
            ("All committed entries identical; the reproduction also writes marginal effects for the original-dictionary run, which the committed file lacks", "None needed"),
        "Manuscript/Manuscript Blocks.json":
            ("Differences are limited to the first selection-log label in Table 2 and absolute figure paths", "None needed"),
    }
    for f in files:
        f["explanation"], f["correction"] = why.get(f["file"], ("", ""))
    pd.DataFrame(files).to_csv(HERE / "File Comparison.csv", index=False)

    # ---------------- value-level reconciliation of every number quoted in the manuscript
    no = dict(flatten(json.loads((croot / "Manuscript/Numbers.json").read_text())))
    nr = dict(flatten(json.loads((root / "Manuscript/Numbers.json").read_text())))
    rows = []
    for k, v in no.items():
        rv = nr.get(k, "not reproduced")
        if isinstance(v, (int, float)) and isinstance(rv, (int, float)):
            d = abs(float(v) - float(rv)) if not (pd.isna(v) and pd.isna(rv)) else 0.0
            st = "match" if d < 1e-9 else ("match to rounding" if d < 5e-4 else "mismatch")
        else:
            d, st = np.nan, "match" if v == rv else "mismatch"
        rows.append({"source": "Manuscript/Numbers.json", "quantity": k, "original": v, "reproduced": rv,
                     "abs_difference": d, "status": st, "explanation": explain(k), "correction": ""})
    with gzip.open(a.data / "Company Facts" / "Financial Facts Long.csv.gz", "rt") as fh:
        n_facts = sum(1 for _ in fh) - 1
    rows.append({"source": "Company Facts/Financial Facts Long.csv.gz", "quantity": "xbrl_fact_rows (row count of facts file)",
                 "original": no["xbrl_fact_rows"], "reproduced": n_facts, "abs_difference": abs(no["xbrl_fact_rows"] - n_facts),
                 "status": "match" if n_facts == no["xbrl_fact_rows"] else "mismatch",
                 "explanation": "Constant in collect numbers.py checked against the data branch file", "correction": ""})
    rec = pd.DataFrame(rows)
    rec.to_csv(HERE / "Reconciliation Report.csv", index=False)
    summary = {"commit_reproduced": COMMIT, "numbers_compared": int(len(rec)),
               "status_counts": rec["status"].value_counts().to_dict(),
               "files_compared": len(files), "files_identical": int(sum(bool(f.get("identical")) for f in files)),
               "files_not_identical": [f["file"] for f in files if not f.get("identical")],
               "python": sys.version.split()[0], "pandas": pd.__version__, "numpy": np.__version__}
    import statsmodels, linearmodels, sklearn
    summary.update(statsmodels=statsmodels.__version__, linearmodels=linearmodels.__version__, sklearn=sklearn.__version__)
    (HERE / "Reproduction Summary.json").write_text(json.dumps(summary, indent=1, default=str))
    print(json.dumps(summary, indent=1, default=str))


if __name__ == "__main__":
    main()
