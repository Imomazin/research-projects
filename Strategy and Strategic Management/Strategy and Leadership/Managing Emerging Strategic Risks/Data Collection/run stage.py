"""Entry point for the GitHub Actions collection pipeline.

Reads the stage name from Run Request.txt, executes it and writes outputs:
small files to the research branch (this checkout) and large raw files to the
data branch, which is checked out into a separate working folder.
"""
from __future__ import annotations

import datetime as dt
import importlib.util
import json
import re
import subprocess
import sys
import traceback
from pathlib import Path
from urllib.parse import urljoin

HERE = Path(__file__).resolve().parent
PROJ = HERE.parent
REPO = PROJ.parents[2]
DATA_BRANCH = "data/strategic-risk"
DATA_DIR = REPO.parent / "databranch"
CACHE = REPO.parent / "httpcache"

spec = importlib.util.spec_from_file_location("edgar", HERE / "edgar.py")
edgar = importlib.util.module_from_spec(spec)
spec.loader.exec_module(edgar)

LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def git(*args, cwd=REPO, check=True):
    return subprocess.run(["git", *args], cwd=cwd, check=check, text=True, capture_output=True)


def prepare_data_branch():
    if DATA_DIR.exists():
        return
    url = git("remote", "get-url", "origin").stdout.strip()
    r = subprocess.run(["git", "clone", "--depth", "1", "--branch", DATA_BRANCH, url, str(DATA_DIR)],
                       text=True, capture_output=True)
    if r.returncode != 0:
        DATA_DIR.mkdir(parents=True)
        git("init", cwd=DATA_DIR)
        git("checkout", "-b", DATA_BRANCH, cwd=DATA_DIR)
        git("remote", "add", "origin", url, cwd=DATA_DIR)
        (DATA_DIR / "README.md").write_text(
            "# Strategic risk raw data\n\nLarge raw extracts for the Strategy and Leadership strategic risk "
            "project. Generated by the collection pipeline on the research branch. Public-domain SEC material.\n")
    for repo_dir in (DATA_DIR,):
        git("config", "user.name", "strategic-risk-pipeline", cwd=repo_dir)
        git("config", "user.email", "actions@users.noreply.github.com", cwd=repo_dir)


def push(repo_dir: Path, branch: str, message: str):
    git("add", "-A", cwd=repo_dir)
    if git("diff", "--cached", "--quiet", cwd=repo_dir, check=False).returncode == 0:
        return
    git("commit", "-m", message, cwd=repo_dir)
    for _ in range(6):
        if git("push", "origin", f"HEAD:{branch}", cwd=repo_dir, check=False).returncode == 0:
            return
        git("pull", "--rebase", "origin", branch, cwd=repo_dir, check=False)
    raise RuntimeError(f"push to {branch} failed")


def links(html: str, base: str, exts=(".xls", ".xlsx", ".csv", ".zip")) -> list[str]:
    out = []
    for href in re.findall(r'href=["\']([^"\']+)["\']', html, flags=re.I):
        full = urljoin(base, href.strip())
        if full.lower().split("?")[0].endswith(exts) and full not in out:
            out.append(full)
    return out


