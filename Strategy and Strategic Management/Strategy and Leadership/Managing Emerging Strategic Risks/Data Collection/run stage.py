PROBE_PAGES = {
    "Geopolitical Risk": "https://www.matteoiacoviello.com/gpr.htm",
    "Economic Policy Uncertainty US": "https://www.policyuncertainty.com/us_monthly.html",
    "Economic Policy Uncertainty Categorical": "https://www.policyuncertainty.com/categorical_epu.html",
    "Economic Policy Uncertainty Global": "https://www.policyuncertainty.com/global_monthly.html",
    "World Uncertainty Index": "https://worlduncertaintyindex.com/data/",
    "Supply Chain Pressure": "https://www.newyorkfed.org/research/policy/gscpi",
}
PROBE_CIKS = {"Apple": 320193, "Microsoft": 789019, "Caterpillar": 18230, "Ford": 37996,
              "Pfizer": 78003, "Walmart": 104169}


def stage_probe(client, out_small: Path, out_large: Path, log: list, **kw):
    manifest = []
    macro_dir = out_large / "Probe" / "Macro"
    macro_dir.mkdir(parents=True, exist_ok=True)
    for name, page in PROBE_PAGES.items():
        html = client.get(page, sec=False)
        if html is None:
            log.append(f"page failed {page}")
            continue
        (macro_dir / f"{name} Page.html").write_bytes(html)
        found = links(html.decode("utf-8", "ignore"), page)
        log.append(f"{name}: {len(found)} data links: {found[:20]}")
        for i, url in enumerate(found[:12]):
            body = client.get(url, sec=False)
            if body is None or len(body) > 60_000_000:
                continue
            ext = url.lower().split("?")[0].rsplit(".", 1)[-1]
            fn = macro_dir / f"{name} File {LETTERS[i]}.{ext}"
            fn.write_bytes(body)
            manifest.append({"name": fn.name, "url": url, "bytes": len(body),
                             "sha256": edgar.sha256_file(fn), "retrieved": now()})
    sec_dir = out_large / "Probe" / "SEC"
    sec_dir.mkdir(parents=True, exist_ok=True)
    for name, url in {
        "Company Tickers Exchange.json": "https://www.sec.gov/files/company_tickers_exchange.json",
        "Frame Assets Calendar Year End.json": "https://data.sec.gov/api/xbrl/frames/us-gaap/Assets/USD/CY2018Q4I.json",
    }.items():
        body = client.get(url)
        if body:
            (sec_dir / name).write_bytes(body)
            manifest.append({"name": name, "url": url, "bytes": len(body), "retrieved": now()})
    idx = client.get("https://www.sec.gov/Archives/edgar/full-index/2019/QTR1/form.idx")
    if idx:
        lines = [l for l in idx.decode("latin-1").splitlines() if l.startswith("10-K ")]
        (sec_dir / "Form Index Tenk Lines Sample.txt").write_text("\n".join(lines[:4000]))
        log.append(f"form.idx 2019Q1 10-K lines: {len(lines)}")
    for firm, cik in PROBE_CIKS.items():
        sub = client.get(f"https://data.sec.gov/submissions/CIK{cik:010d}.json")
        if not sub:
            log.append(f"submissions failed {firm}")
            continue
        (sec_dir / f"{firm} Submissions.json").write_bytes(sub)
        data = json.loads(sub)
        rec = data["filings"]["recent"]
        tenks = [i for i, f in enumerate(rec["form"]) if f == "10-K"]
        picked = []
        for i in tenks:
            yr = rec["reportDate"][i][:4]
            if yr in ("2018", "2019", "2023") and yr not in [p[0] for p in picked]:
                picked.append((yr, i))
        for yr, i in picked:
            acc = rec["accessionNumber"][i].replace("-", "")
            url = f"https://www.sec.gov/Archives/edgar/data/{cik}/{acc}/{rec['primaryDocument'][i]}"
            body = client.get(url)
            word = {"2018": "Eighteen", "2019": "Nineteen", "2023": "Twentythree"}[yr]
            if body:
                (sec_dir / f"{firm} Tenk {word}.htm").write_bytes(body)
                log.append(f"{firm} {yr} {url} {len(body)} bytes")
        if firm in ("Apple", "Caterpillar"):
            facts = client.get(f"https://data.sec.gov/api/xbrl/companyfacts/CIK{cik:010d}.json")
            if facts:
                (sec_dir / f"{firm} Company Facts.json").write_bytes(facts)
    (out_large / "Probe" / "Probe Manifest.json").write_text(json.dumps(manifest, indent=1))


STAGES = {"probe": stage_probe}


def main():
    request = (HERE / "Run Request.txt").read_text()
    stage = re.search(r"stage:\s*(\S+)", request).group(1)
    args = dict(re.findall(r"(\w+):\s*(\S+)", request))
    prepare_data_branch()
    client = edgar.Client(CACHE)
    log: list[str] = [f"stages {stage} started {now()}", f"request: {request.strip()}"]
    status = "completed"
    spec2 = importlib.util.spec_from_file_location("stages", HERE / "collection stages.py")
    stages = importlib.util.module_from_spec(spec2)
    spec2.loader.exec_module(stages)
    registry = {**stages.STAGES, "probe": stage_probe}
    for name in stage.split(","):
        try:
            log.append(f"--- {name} {now()}")
            registry[name](client, PROJ, DATA_DIR, log, **{k: v for k, v in args.items() if k != "stage"})
        except Exception:
            status = "failed"
            log.append(f"stage {name} failed")
            log.append(traceback.format_exc())
    log.extend(client.log[-400:])
    log.append(f"stage {stage} {status} {now()}")
    logdir = HERE / "Run Logs"
    logdir.mkdir(exist_ok=True)
    (logdir / f"{stage.replace(',', ' ').title()} Log.txt").write_text("\n".join(log))
    (logdir / "Latest Status.txt").write_text(f"{stage} {status} {now()}\n")
    try:
        push(DATA_DIR, DATA_BRANCH, f"Pipeline stage {stage} {status}")
    except Exception:
        status = "failed"
        (logdir / "Data Push Error.txt").write_text(traceback.format_exc())
        (logdir / "Latest Status.txt").write_text(f"{stage} {status} data push {now()}\n")
    git("config", "user.name", "strategic-risk-pipeline")
    git("config", "user.email", "actions@users.noreply.github.com")
    push(REPO, "research/strategic-risk", f"Pipeline stage {stage} {status}")
    if status != "completed":
        sys.exit(1)


if __name__ == "__main__":
    main()
